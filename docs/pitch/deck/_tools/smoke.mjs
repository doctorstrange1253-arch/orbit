import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const PptxGenJS = require('pptxgenjs');
const sharp = require('sharp');
const ExcelJS = require('exceljs');
const out = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), 'smoke');
const pptx = new PptxGenJS();
pptx.defineLayout({ name: 'READ', width: 13.333, height: 7.5 });
pptx.layout = 'READ';
pptx.author = 'Orbit pitch preparation';
pptx.subject = 'Isolated renderer smoke test, sample data';
pptx.theme = { headFontFace: 'Segoe UI', bodyFontFace: 'Segoe UI', lang: 'en-IN' };
await sharp({ create: { width: 400, height: 240, channels: 4, background: '#FAF8F4' } }).png().toFile(path.join(out, 'image-smoke.png'));
const slide = pptx.addSlide();
slide.background = { color: 'FAF8F4' };
slide.addShape(pptx.ShapeType.rect, { x: 0.35, y: 1.15, w: 12.633, h: 5.82, fill: { color: 'FFFFFF' }, line: { color: 'E4DED3', width: 0.75 } });
slide.addText('Orbit renderer smoke test', { x: 0.45, y: 0.4, w: 11, h: 0.5, fontFace: 'Segoe UI Semibold', fontSize: 28, color: '101828', margin: 0, fit: 'none' });
slide.addText('11.5 pt body | 10.5 pt table | 8 pt source', { x: 0.6, y: 1.5, w: 9, h: 0.3, fontSize: 11.5, color: '101828', margin: 0, fit: 'none' });
slide.addText('123,456.78', { x: 0.6, y: 2, w: 8, h: 1.2, fontSize: 56, color: '101828', margin: 0, fit: 'none' });
slide.addText('SAMPLE DATA', { x: 0.6, y: 3.12, w: 4, h: 0.2, fontSize: 8, color: '101828', margin: 0, fit: 'none' });
slide.addImage({ path: path.join(out, 'image-smoke.png'), x: 10, y: 1.5, w: 2, h: 1.2 });
slide.addChart(pptx.ChartType.bar, [{ name: 'Sample series', labels: ['A', 'B'], values: [20, 80] }], { x: 0.6, y: 3.5, w: 6, h: 2.4, showLegend: false, showValue: true, chartColors: ['0876AF'], catAxisLabelFontFace: 'Segoe UI', catAxisLabelFontSize: 10.5, valAxisLabelFontSize: 10.5 });
slide.addNotes('Smoke only: native text, image, chart and speaker notes. No actual product or financial evidence.');
await pptx.writeFile({ fileName: path.join(out, 'native-smoke.pptx'), compression: true });
const book = new ExcelJS.Workbook();
const sheet = book.addWorksheet('Smoke');
sheet.addRow(['Input', 'Value']);
sheet.addRow(['A', 20]);
sheet.addRow(['B', 80]);
sheet.getCell('B4').value = { formula: 'SUM(B2:B3)', result: 100 };
await book.xlsx.writeFile(path.join(out, 'workbook-smoke.xlsx'));
const loaded = new ExcelJS.Workbook();
await loaded.xlsx.readFile(path.join(out, 'workbook-smoke.xlsx'));
if (loaded.getWorksheet('Smoke').getCell('B4').value.result !== 100) throw Error('Workbook smoke result mismatch');
const meta = await sharp(path.join(out, 'image-smoke.png')).metadata();
if (meta.width !== 400 || meta.height !== 240) throw Error('Image smoke dimension mismatch');
console.log(JSON.stringify({ pptxBytes: fs.statSync(path.join(out, 'native-smoke.pptx')).size, workbookBytes: fs.statSync(path.join(out, 'workbook-smoke.xlsx')).size, image: [meta.width, meta.height], formulaCache: 100, nativeRender: 'NOT_RUN' }));
