#!/usr/bin/env node
/**
 * probe-env — detects OS, shell, cwd, and tool versions, checks which commands
 * from the Section 5.3 table exist, and writes a summary to .agent/ENVIRONMENT.md.
 * Node-only, no dependencies. Run: node scripts/agent/probe-env
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');

function run(cmd) {
  try {
    return execSync(cmd, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  } catch (e) {
    return null;
  }
}

function cmdExists(name) {
  // Node on Windows spawns cmd.exe, where `where` is the lookup tool.
  // On POSIX, use `command -v`. Try both defensively.
  if (process.platform === 'win32') {
    const r = run(`where ${name} 2>nul`);
    return r ? r.split('\n')[0].trim() : null;
  }
  const r = run(`command -v ${name} 2>/dev/null`);
  return r ? r : null;
}

const COMMANDS = [
  'ls', 'dir', 'find', 'rg', 'grep', 'git', 'cat', 'type', 'head', 'sed',
  'wc', 'tree', 'curl', 'wget', 'jq', 'node', 'npm', 'npx', 'python3', 'python', 'py',
  'pwsh', 'powershell', 'xcopy', 'robocopy', 'tar', 'unzip', '7z',
];

const found = {};
for (const c of COMMANDS) found[c] = cmdExists(c);

const lines = [];
lines.push('# ENVIRONMENT — machine truth (generated by scripts/agent/probe-env)');
lines.push('');
lines.push(`Generated: ${new Date().toISOString()}`);
lines.push(`Project root (script location): ${ROOT}`);
lines.push('');
lines.push('## Core');
lines.push(`- OS: ${process.platform} ${run('uname -srm') || ''}`.trim());
lines.push(`- Shell (this script): bash via Node; process.env.SHELL=${process.env.SHELL || 'unset'}; COMSPEC=${process.env.COMSPEC || 'unset'}`);
lines.push(`- cwd at probe: ${process.cwd()}`);
lines.push(`- node: ${process.version}`);
lines.push(`- npm: ${run('npm -v') || 'missing'}`);
lines.push(`- git: ${run('git --version') || 'missing'}`);
lines.push(`- python3: ${run('python3 --version') || run('python --version') || 'missing'}`);
lines.push('');
lines.push('## Command availability (command -v)');
for (const c of COMMANDS) {
  lines.push(`- ${c}: ${found[c] ? 'YES -> ' + found[c] : 'no'}`);
}
lines.push('');
lines.push('## Working fallbacks on this machine (recorded after probing)');
lines.push('| Need | Works here | Fallback |');
lines.push('|---|---|---|');
lines.push('| List dir | ls -la | Get-ChildItem -Force |');
lines.push('| Find file | find . -name | scripts/agent/find-file |');
lines.push('| Search text | grep -rn / rg if present | scripts/agent/find-file --content |');
lines.push('| Read file | file viewer tool | cat / Get-Content |');
lines.push('| Write file | Write tool | Node fs.writeFileSync |');
lines.push('| Run JS | node | npx --yes |');
lines.push('| JSON | node -e | python -c |');
lines.push('| HTTP | curl | node fetch |');
lines.push('| Git | git (repo root: D:/orbit-main/orbit-main) | — |');
lines.push('');
lines.push('## Notes');
lines.push('- Bash tool on this machine is Git Bash (MINGW64); Windows paths need forward slashes (d:/orbit-main/...). `cd D:\\...` fails — always use forward slashes or POSIX /d/... paths.');
lines.push('- PowerShell tool exists separately (powershell.exe 5.1); do not mix syntax.');
lines.push('- The harness primary working directory is the project root D:/orbit-main/orbit-main; it is a git repo on branch feature/orbit-v3-foundation.');
lines.push('- Parent D:/orbit-main is NOT a git repo and contains stray tmp-* skill clones (see docs/progress/recovery-report.md).');

const out = path.join(ROOT, '.agent', 'ENVIRONMENT.md');
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log('WROTE', out);
console.log(lines.filter(l => l.startsWith('- ') && (l.includes('node:') || l.includes('npm:') || l.includes('git:') || l.includes('python') || l.includes('OS:'))).join('\n'));
